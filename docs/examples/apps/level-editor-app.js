    // ---- "new from template" flow -----------------------------------------
    // loadSceneTemplate replaces the current scene via the same _setScene-
    // shaped restore path already used by the window.__debug _setScene API
    // below (normalizeScene + clear selection + re-render), so a template
    // load goes through the exact same corruption-safe/migration path a
    // saved-scene load does. Pushes an undo snapshot first so "new from
    // template" is itself undoable, same as any other scene mutation here.
    async function loadSceneTemplate(templateFile) {
        try {
            const { raw, schemaVersion } = await fetchSceneTemplate(templateFile);
            if (schemaVersion > SCHEMA_VERSION) {
                // Newer-than-supported template: normalizeScene() already
                // keeps whatever objects still parse rather than discarding
                // the scene, so still attempt the load but flag it loudly
                // instead of silently pretending nothing happened.
                flashRef && flashRef(t('leveleditor.templateNewerSchema', 'template targets a newer schema version — loading best-effort'));
            }
            undoStack.push(scene);
            scene = normalizeScene(raw);
            if (scene._clampedOnLoad) {
                delete scene._clampedOnLoad;
                flashRef && flashRef(t('leveleditor.sceneClamped', 'some objects had out-of-range coordinates — clamped to the canvas on load'));
            }
            selected.clear();
            dirty = true;
            renderInspector();
            renderChains();
            draw();
            updateStatus();
            flashRef && flashRef(t('leveleditor.templateLoaded', 'template loaded'));
        } catch (e) {
            saveError(t('leveleditor.templateLoadFailed', 'template load failed: ') + ((e && e.message) || e));
        }
    }

