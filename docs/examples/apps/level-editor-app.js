// ---- scene templates (docs/templates/scenes/) --------------------------
// Distinct from docs/lib/templates.js's INSTANCE-level templates (whole
// instance: workspace/env/schemaVersion/overrides). This is scoped
// specifically to level-editor scene starting points, same
// no-directory-listing-on-a-static-server constraint (hardcoded manifest
// fetched at runtime, see docs/lib/templates.js's own KNOWN_TEMPLATE_FILES
// comment for the identical reasoning). Resolve relative to THIS module's
// URL so it works regardless of the page that imported it.
const SCENE_TEMPLATES_BASE = new URL('../templates/scenes/', import.meta.url);

async function fetchSceneTemplateManifest() {
    const res = await fetch(new URL('manifest.json', SCENE_TEMPLATES_BASE));
    if (!res.ok) throw new Error('manifest fetch failed: ' + res.status);
    return res.json();
}

// Fetches one template's scene JSON. Tracks the manifest-declared
// schemaVersion so a future scene-format bump can migrate/warn instead of
// silently loading a stale-shaped template — normalizeScene() already
// upgrades whatever schemaVersion it finds via MIGRATIONS, so a template
// pinned to an old version still loads safely; this just surfaces the
// version to the caller for future-proofing (e.g. a UI warning) rather than
// hiding it.
async function fetchSceneTemplate(filename) {
    const res = await fetch(new URL(filename, SCENE_TEMPLATES_BASE));
    if (!res.ok) throw new Error('template fetch failed: ' + filename + ' ' + res.status);
    const raw = await res.json();
    return { raw, schemaVersion: typeof raw.schemaVersion === 'number' ? raw.schemaVersion : 1 };
}

// ---- code-escape-hatch: "view as code" ----------------------------------
// Generates a readable, syntactically-valid JS snippet showing roughly what
// a hand-written app factory consuming this scene would look like, matching
// docs/snake-app.js's reference shape (export function createXApp({instance})
// returning {node, dispose}). This is deliberately NOT full app-file
// codegen (no event wiring, no persistence, no playtest loop) — it's a
// readable "shape of the code" view for power users, consistent with
// thebird's existing terminal/cli-app code-facing surfaces (see
// docs/cli-app.js).
function jsStringLiteral(s) {
    return JSON.stringify(String(s));
}

function generateSceneCode(scn) {
    const objs = (scn && Array.isArray(scn.objects)) ? scn.objects : [];
    const objLines = objs.map(o => {
        return '        { id: ' + jsStringLiteral(o.id) + ', kind: ' + jsStringLiteral(o.kind) +
            ', x: ' + o.x + ', y: ' + o.y + ', w: ' + o.w + ', h: ' + o.h +
            ', color: ' + jsStringLiteral(o.color) + ', label: ' + jsStringLiteral(o.label || '') + ' },';
    });
    const drawKinds = 'if (o.kind === \'circle\' || o.kind === \'goal\') {\n' +
        '                ctx.beginPath();\n' +
        '                ctx.arc(o.x + o.w / 2, o.y + o.h / 2, Math.min(o.w, o.h) / 2, 0, Math.PI * 2);\n' +
        '                ctx.fill();\n' +
        '            } else {\n' +
        '                ctx.fillRect(o.x, o.y, o.w, o.h);\n' +
        '            }';
    return [
        '// Generated by level-editor-app.js "view as code" — a readable sketch of',
        '// the hand-written app factory this scene implies (see docs/snake-app.js',
        '// for the real reference shape). NOT a runnable standalone file: wire it',
        '// into apps.js\'s createAppRegistry the same way snake-app.js is wired.',
        '',
        "import { t } from '../../vendor/i18n.js';",
        '',
        '// schemaVersion: ' + (scn && typeof scn.schemaVersion === 'number' ? scn.schemaVersion : 1),
        'const SCENE_OBJECTS = [',
        ...objLines,
        '];',
        '',
        'export function createMySceneApp({ instance }) {',
        "    const node = document.createElement('div');",
        "    node.className = 'app-pane';",
        "    node.dataset.component = 'my-scene-app';",
        '',
        "    const cv = document.createElement('canvas');",
        '    cv.width = 480; cv.height = 360;',
        "    const ctx = cv.getContext('2d');",
        '    node.append(cv);',
        '',
        '    function draw() {',
        "        ctx.clearRect(0, 0, cv.width, cv.height);",
        '        for (const o of SCENE_OBJECTS) {',
        '            ctx.fillStyle = o.color;',
        '            ' + drawKinds,
        '        }',
        '    }',
        '    draw();',
        '',
        '    return {',
        '        node,',
        '        dispose: () => {},',
        '    };',
        '}',
        '',
    ].join('\n');
}

// level-editor-app.js — a genuine no-code game/level editor: place objects on
// a canvas, edit their properties in a live-bound inspector, save/load as a
// versioned scene-graph JSON via the per-instance fs, and export a portable
// .json file. This is the first real answer to "can a non-coder build
// anything resembling a game via thebird's GUI alone" — every prior app
// (snake, boids) was 100% hand-coded JS with zero authoring tooling.
//
// Scene-graph schema (versioned so future format changes never silently
// break old saves — mirrors os-shell.js's own versioned-snapshot pattern):
//   { schemaVersion: 1, objects: [{ id, name, kind, x, y, w, h, color, label }] }
//
// Persistence follows instance-fs's own debounced-flush contract (documented
// in notes-app.js/snake-app.js): writeJson only debounces to IDB after
// 250ms, so an explicit flush() is required before any point where the
// change must be guaranteed durable (window close, explicit save).

const SCENE_DIR = 'level-editor';
const SCHEMA_VERSION = 1;
const KIND_DEFAULTS = {
    rect: { w: 40, h: 40, color: '#4a90d9', label: 'block' },
    circle: { w: 32, h: 32, color: '#d94a4a', label: 'actor' },
    goal: { w: 28, h: 28, color: '#4ad97a', label: 'goal' },
    sprite: { w: 40, h: 40, color: '#9b59b6', label: 'sprite' },
};

// ---- event-chain authoring constants --------------------------------------
