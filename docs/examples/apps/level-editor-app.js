const CHAIN_OBJECT_PROPS = ['x', 'y', 'w', 'h', 'color', 'label'];
const CHAIN_COMPARE_OPS = ['==', '!=', '<', '>', '<=', '>='];

function emptyScene() {
    return { schemaVersion: SCHEMA_VERSION, objects: [], revision: 0 };
}

// Corrupt/malformed-save fallback: mirrors instance-fs's own
// fs.readJson(path, null) null-fallback pattern (snake-app.js HS_PATH).
// A future schema bump adds a migration branch here instead of breaking load.
// Canvas is a fixed 480x360 (see `cv.width = 480; cv.height = 360;` below);
// out-of-bounds coordinates/sizes are clamped to this range so a
// corrupted-but-technically-valid scene.json (e.g. x: -999999 or w: 1e9,
// both Number.isFinite-true) can't silently produce off-canvas objects that
// render nothing and get mistaken for an empty scene with no warning shown.
const SCENE_CANVAS_W = 480;
const SCENE_CANVAS_H = 360;
const MAX_OBJECT_DIM = 4096; // generous cap, well above the visible canvas

function normalizeScene(raw) {
    if (!raw || typeof raw !== 'object' || !Array.isArray(raw.objects)) return emptyScene();
    let scn = raw;
    if (typeof scn.schemaVersion !== 'number') scn = { ...scn, schemaVersion: 1 };
    if (scn.schemaVersion < SCHEMA_VERSION) scn = migrateScene(scn);
    // Still-unknown/newer version: keep whatever objects parse as valid
    // rather than discarding the whole scene.
    let clamped = false;
    const objects = scn.objects
        .filter(o => o && typeof o === 'object' && typeof o.id === 'string' && Number.isFinite(o.x) && Number.isFinite(o.y))
        .map(o => {
            const defaults = KIND_DEFAULTS[o.kind] || KIND_DEFAULTS.rect;
            const rawW = Number.isFinite(o.w) ? o.w : defaults.w;
            const rawH = Number.isFinite(o.h) ? o.h : defaults.h;
            const w = Math.min(Math.max(rawW, 1), MAX_OBJECT_DIM);
            const h = Math.min(Math.max(rawH, 1), MAX_OBJECT_DIM);
            const x = Math.min(Math.max(o.x, -MAX_OBJECT_DIM), SCENE_CANVAS_W + MAX_OBJECT_DIM);
            const y = Math.min(Math.max(o.y, -MAX_OBJECT_DIM), SCENE_CANVAS_H + MAX_OBJECT_DIM);
            if (x !== o.x || y !== o.y || w !== rawW || h !== rawH) clamped = true;
            return {
                id: o.id,
                name: typeof o.name === 'string' ? o.name : o.id,
                kind: KIND_DEFAULTS[o.kind] ? o.kind : 'rect',
                x, y, w, h,
                color: typeof o.color === 'string' ? o.color : defaults.color,
                label: typeof o.label === 'string' ? o.label : '',
                ...(o.kind === 'sprite' && typeof o.assetPath === 'string' ? { assetPath: o.assetPath } : {}),
            };
        });
    // Optional event chains (docs/lib/event-chain.js graphs, executed during
    // playtest by docs/lib/event-chain-runtime.js). SCHEMA_VERSION stays 1:
    // `chains` is optional and absent by default, so old saves load unchanged
    // and older code reading a chains-bearing save simply ignores the key.
    // Each entry is validated through normalizeEventChain (never throws —
    // malformed nodes/edges are dropped, cyclic graphs go inert at runtime).
    const chains = Array.isArray(scn.chains) ? scn.chains.map(normalizeEventChain) : null;
    return {
        // Use migrateScene's actual resulting version, not the target
        // SCHEMA_VERSION unconditionally: if migrateScene bailed early
        // (no MIGRATIONS step for an intermediate version), scn.schemaVersion
        // stays at the last-reached version so a later load retries
        // migration instead of the file being falsely marked current.
        schemaVersion: typeof scn.schemaVersion === 'number' ? scn.schemaVersion : SCHEMA_VERSION,
        objects,
        revision: Number.isFinite(scn.revision) ? scn.revision : 0,
        ...(chains ? { chains } : {}),
        ...(clamped ? { _clampedOnLoad: true } : {}),
    };
}

// Migration scaffolding: no format change has shipped yet (SCHEMA_VERSION
// has only ever been 1), so MIGRATIONS is empty today — but the landing pad
// exists so a future bump adds a fromVersion->fn entry instead of a
// bespoke one-off branch. migrateScene walks fromVersion..SCHEMA_VERSION-1
// applying each step in order.
const MIGRATIONS = {
    // 1: (scene) => ({ ...scene, schemaVersion: 2, /* transform here */ }),
};

function migrateScene(scene) {
    let s = scene;
    while (s.schemaVersion < SCHEMA_VERSION) {
        const step = MIGRATIONS[s.schemaVersion];
        if (!step) break; // no known path forward; leave at last-migrated version
        s = step(s);
    }
    return s;
}

function newId() {
    return 'obj-' + Date.now().toString(36) + '-' + shortUid(6);
}

// ---- reusable scene playtest runner ------------------------------------
// Extracted from level-editor-app.js's own startPlaytest/stopPlaytest so
// game-player-app.js (and any future scene consumer) can run a saved scene
// WITHOUT depending on the editor's DOM/toolbar/inspector. The simulation
// is ECS-driven (docs/lib/ecs.js over @spoint/ecs): scene objects become
// entities (id preserved) with position/size/render/meta components, and
// per-frame behavior is two systems — inputMovementSystem (the exact
// arrow-key "actor" movement the playtest has always had) and chainSystem
// (runs the scene's optional `chains` event graphs through
// docs/lib/event-chain-runtime.js). Render reads entity components back in
// original scene order, so a scene WITHOUT chains is pixel-equivalent to
// the pre-ECS loop. Operates on a deep clone of the input scene (never
// mutates the caller's object), mirroring the editor's zero-state-leakage
// guarantee. Returns { stop(), reset(), get scene() } so a caller can
// stop/reset/inspect the live playtest state exactly like the editor's
// window.__debug API did.

// Playtest ECS component names (docs/lib/ecs.js string-typed components).
const PT_POSITION = 'position';
const PT_SIZE = 'size';
const PT_RENDER = 'render'; // { color, kind } — everything the draw pass needs
const PT_META = 'meta';     // { name, label, assetPath? } — everything else

function runScenePlaytest(scene, canvas, opts = {}) {
    const ctx2d = canvas.getContext('2d');
    const onError = typeof opts.onError === 'function' ? opts.onError : () => {};
    const originalScene = scene;
    let playScene = cloneDeep(originalScene);
    const poller = createInputPoller();
    poller.attachDom(opts.inputTarget || canvas);
    const loop = createGameLoop(canvas, { fixedDt: 1000 / 60 });
    // Register this playtest session as a holder of the module-level shared
    // AudioContext (event-chain-runtime.js) exactly once, paired with the
    // single closeSharedAudioContext() call in stop() below -- so this
    // session's stop() only actually tears down the shared context once
    // every other concurrently-running playtest session has also released
    // it, instead of unconditionally killing audio for all of them.
    acquireSharedAudioContext();

    // ---- ECS world (rebuilt from playScene on every reset) ----------------
    // The world is the single runtime store: the render pass and the event
    // chains both read entity components, never playScene.objects.
    // entityOrder preserves the scene's original object order so the render
    // pass draws in exactly the same sequence the pre-ECS loop did (pixel
    // parity); destroyed objects simply drop out of it.
    let world = null;
    let entityOrder = [];
    let chainRunners = [];

    // Scene-object-shaped live view of one entity — the same field set
    // playScene.objects entries carry ({id, name, kind, x, y, w, h, color,
    // label, assetPath?}), read straight out of the components.
    function objectView(id) {
        const pos = world.getComponent(id, PT_POSITION);
        const size = world.getComponent(id, PT_SIZE);
        const rend = world.getComponent(id, PT_RENDER);
        const meta = world.getComponent(id, PT_META) || {};
        return {
            id,
            name: meta.name !== undefined ? meta.name : id,
            kind: rend.kind,
            x: pos.x, y: pos.y,
            w: size.w, h: size.h,
            color: rend.color,
            label: meta.label !== undefined ? meta.label : '',
            ...(meta.assetPath !== undefined ? { assetPath: meta.assetPath } : {}),
        };
    }

    // Chain-facing context: the event-chain runtime's ctx contract (see
    // docs/lib/event-chain-runtime.js's header). Reads/writes route into the
    // ECS world, so chain actions and the render pass always agree.
    const chainCtx = {
        getObjects() {
            const objects = [];
            for (const id of entityOrder) {
                if (world.hasComponent(id, PT_RENDER)) objects.push(objectView(id));
            }
            return objects;
        },
        setObjectProp(id, prop, value) {
            if (!world.hasComponent(id, PT_RENDER)) return;
            if (prop === 'x' || prop === 'y') {
                world.getComponent(id, PT_POSITION)[prop] = value;
            } else if (prop === 'w' || prop === 'h') {
                world.getComponent(id, PT_SIZE)[prop] = value;
            } else if (prop === 'color' || prop === 'kind') {
                world.getComponent(id, PT_RENDER)[prop] = value;
            } else {
                world.getComponent(id, PT_META)[prop] = value;
            }
        },
        removeObject(id) { world.destroyEntity(id); },
        isKeyDown(key) { return poller.isDown(key); },
        get width() { return canvas.width; },
        get height() { return canvas.height; },
        onError,
    };

    // Exact parity with the pre-ECS update(): only kind==='circle' objects
    // (the "actor" default, see KIND_DEFAULTS) move, same speed, same canvas
    // clamp. The kind test reads the LIVE render component every frame (not
    // a build-time tag) so a chain setProperty flipping an object's kind
    // mid-play behaves the way the old per-frame `o.kind !== 'circle'`
    // check would have.
    function inputMovementSystem(w, dt) {
        const speed = 60 / 1000;
        for (const id of w.query(PT_POSITION, PT_SIZE, PT_RENDER)) {
            const rend = w.getComponent(id, PT_RENDER);
            if (rend.kind !== 'circle') continue;
            let dx = 0, dy = 0;
            if (poller.isDown('ArrowLeft')) dx -= 1;
            if (poller.isDown('ArrowRight')) dx += 1;
            if (poller.isDown('ArrowUp')) dy -= 1;
            if (poller.isDown('ArrowDown')) dy += 1;
            if (!dx && !dy) continue;
            const pos = w.getComponent(id, PT_POSITION);
            const size = w.getComponent(id, PT_SIZE);
            pos.x = Math.max(0, Math.min(canvas.width - size.w, pos.x + dx * speed * dt));
            pos.y = Math.max(0, Math.min(canvas.height - size.h, pos.y + dy * speed * dt));
        }
    }

    // Runs the scene's event chains. No chains -> chainRunners is empty and
    // this system is a no-op, which is the regression-parity path.
    function chainSystem(w, dt) {
        for (const r of chainRunners) r.update(dt);
    }

    function buildWorld() {
        world = createWorld();
        entityOrder = [];
        // Dedupe object ids before creating entities: ecs.js's createEntity()
        // throws on a repeated id, and buildWorld() runs outside any
        // try/catch (unlike update()/render() below), so an id collision —
        // from a hand-edited scene JSON, a clone-without-regenerating-id
        // editor bug, or any other malformed input — would otherwise crash
        // the whole playtest on both the initial build and every reset().
        // Mirrors normalizeScene's recover-don't-throw philosophy: keep the
        // first object for a given id, silently drop later duplicates.
        const seenIds = new Set();
        for (const o of playScene.objects) {
            if (seenIds.has(o.id)) continue;
            seenIds.add(o.id);
            world.createEntity(o.id);
            world.addComponent(o.id, PT_POSITION, { x: o.x, y: o.y });
            world.addComponent(o.id, PT_SIZE, { w: o.w, h: o.h });
            world.addComponent(o.id, PT_RENDER, { color: o.color, kind: o.kind });
            const meta = { name: o.name, label: o.label };
            if (o.assetPath !== undefined) meta.assetPath = o.assetPath;
            world.addComponent(o.id, PT_META, meta);
            entityOrder.push(o.id);
        }
        world.addSystem(inputMovementSystem, 0);
        world.addSystem(chainSystem, 1);
        chainRunners = createChainRunners(playScene.chains, chainCtx);
    }

    function update(dt) {
        try {
            world.step(dt);
        } catch (e) { onError(e); }
    }

    function render() {
        try {
            ctx2d.clearRect(0, 0, canvas.width, canvas.height);
            ctx2d.fillStyle = '#102010';
            ctx2d.fillRect(0, 0, canvas.width, canvas.height);
            for (const id of entityOrder) {
                if (!world.hasComponent(id, PT_RENDER)) continue;
                const pos = world.getComponent(id, PT_POSITION);
                const size = world.getComponent(id, PT_SIZE);
                const rend = world.getComponent(id, PT_RENDER);
                ctx2d.fillStyle = rend.color;
                if (rend.kind === 'circle' || rend.kind === 'goal') {
                    ctx2d.beginPath();
                    ctx2d.arc(pos.x + size.w / 2, pos.y + size.h / 2, Math.min(size.w, size.h) / 2, 0, Math.PI * 2);
                    ctx2d.fill();
                } else {
                    ctx2d.fillRect(pos.x, pos.y, size.w, size.h);
                }
            }
        } catch (e) { onError(e); }
    }

    buildWorld();
    loop.onUpdate(update);
    loop.onRender(render);
    loop.start();

    return {
        stop() { try { loop.stop(); } catch { /* swallow: game loop already stopped/never started */ } try { poller.dispose(); } catch { /* swallow: input poller already disposed */ } try { closeSharedAudioContext(); } catch { /* swallow: audio teardown is best-effort */ } },
        reset() { playScene = cloneDeep(originalScene); buildWorld(); },
        get scene() { return { ...playScene, objects: chainCtx.getObjects() }; },
    };
}

// ---- generic undo/redo stack -------------------------------------------
// Dependency-free, deep-clone-based (structuredClone if present, else
// JSON round-trip). Deliberately inlined here rather than split into
// docs/lib/undo-stack.js: it's ~15 lines, has zero DOM/app coupling, and
// no other thebird app has asked for undo yet — pulling it out into a
// shared lib file before a second consumer exists would be speculative
// generality. If/when a second app wants undo, hoist this verbatim into
// docs/lib/undo-stack.js at that point (documented here so that decision
// point is easy to find).
function cloneDeep(v) {
    if (typeof structuredClone === 'function') { try { return structuredClone(v); } catch { /* swallow: value not structured-cloneable (e.g. contains a function), fall through to JSON round-trip */ } }
    return JSON.parse(JSON.stringify(v));
}

function createUndoStack(maxSize = 50) {
    let past = [];
    let future = [];
    return {
        push(snapshot) {
            past.push(cloneDeep(snapshot));
            if (past.length > maxSize) past.shift();
            future = []; // any new action invalidates the redo branch
        },
        undo(current) {
            if (!past.length) return null;
            const prev = past.pop();
            if (current !== undefined) future.push(cloneDeep(current));
            return prev;
        },
        redo(current) {
            if (!future.length) return null;
            const next = future.pop();
            if (current !== undefined) past.push(cloneDeep(current));
            return next;
        },
        canUndo() { return past.length > 0; },
        canRedo() { return future.length > 0; },
    };
}

