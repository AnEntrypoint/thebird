#!/usr/bin/env node
// Generates the vendor CSS <link> stack + node-builtin importmap shared by
// docs/index.html and docs/os.html, and rewrites both files in place between
// marker comments so the two documents never drift out of sync. Re-running
// this script is idempotent (it only replaces the bounded region).
//
// The vendor file list here mirrors what scripts/refresh-design.mjs copies
// into docs/vendor/ (kits/os/*.css) plus the xterm.css / sqlite-shim /
// busybase / node-builtin shim / xstate / acptoapi wiring that
// docs/index.html and docs/os.html have always hand-duplicated.
// anentrypoint-design's own 247420.css loads live from raw.githack.com's
// GitHub @main mirror instead of the local vendor copy, so its own SDK
// build always tracks latest without a re-vendoring step for this one
// file. Not unpkg (npm publishing stopped, stale resolution) or jsDelivr's
// gh/... equivalent (caches a @main branch reference up to 12h regardless
// of purge) — githack fetches straight from GitHub with a 60s max-age.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DOCS = join(ROOT, 'docs');

const LIVE_CSS_FILES = [
  'https://raw.githack.com/AnEntrypoint/design/main/dist/247420.css',
];

const VENDOR_CSS_FILES = [
  'vendor/kits/os/colors_and_type.css',
  'vendor/kits/os/app-shell.css',
  'vendor/kits/os/theme.css',
  'vendor/kits/os/freddie-dashboard.css',
  'vendor/kits/os/app-panes.css',
  'vendor/xterm.css',
];

const IMPORTMAP = {
  imports: {
    'sqlite3-wasm': './lib/sqlite-shim.js',
    '@sqlite.org/sqlite-wasm': './lib/sqlite-shim.js',
    '@libsql/libsql-wasm-experimental': './lib/sqlite-shim.js',
    busybase: './vendor/busybase/embedded.js',
    'busybase/embedded': './vendor/busybase/embedded.js',
    'node:fs': './vendor/esm/node/fs.mjs',
    'node:path': './vendor/esm/node/path.mjs',
    'node:crypto': './vendor/esm/node/crypto.mjs',
    'node:buffer': './vendor/esm/node/buffer.mjs',
    'node:process': './vendor/esm/node/process.mjs',
    'node:url': './vendor/esm/node/url.mjs',
    'node:os': './vendor/esm/node/os.mjs',
    'node:child_process': './vendor/esm/node/child_process.mjs',
    // Required by the vendored freddie browser bundle's top-level
    // `import { createRequire } from "node:module"` — dropping this entry
    // (as happened in the d26558f regeneration) makes the whole bundle
    // unresolvable and freddie-loader's throw takes down the shell mount.
    'node:module': './vendor/esm/node/module.mjs',
    'node:events': './vendor/esm/node/events.mjs',
    'node:util': './vendor/esm/node/util.mjs',
    'node:stream': './vendor/esm/node/stream.mjs',
    xstate: './vendor/xstate.js',
    acptoapi: './lib/acptoapi-browser.js',
  },
};

const START = '<!-- VENDOR-HEAD:START (generated by scripts/gen-vendor-head.mjs — do not hand-edit) -->';
const END = '<!-- VENDOR-HEAD:END -->';

function renderFragment() {
  const cssLines = [...LIVE_CSS_FILES, ...VENDOR_CSS_FILES].map((f) => `<link rel="stylesheet" href="${f}">`).join('\n');
  const importmapJson = JSON.stringify(IMPORTMAP, null, 2);
  return `${START}\n${cssLines}\n<script type="importmap">\n${importmapJson}\n</script>\n${END}`;
}

function rewrite(path, fragment) {
  const src = readFileSync(path, 'utf8');
  const startIdx = src.indexOf(START);
  const endIdx = src.indexOf(END);
  if (startIdx === -1 || endIdx === -1) {
    throw new Error(`${path}: missing VENDOR-HEAD markers (expected "${START}" ... "${END}")`);
  }
  const before = src.slice(0, startIdx);
  const after = src.slice(endIdx + END.length);
  const next = before + fragment + after;
  if (next !== src) {
    writeFileSync(path, next);
    console.log(`updated ${path}`);
  } else {
    console.log(`unchanged ${path}`);
  }
}

const fragment = renderFragment();

mkdirSync(join(DOCS, 'vendor'), { recursive: true });
writeFileSync(join(DOCS, 'vendor', 'head-block.html'), fragment + '\n');
console.log('wrote docs/vendor/head-block.html');

rewrite(join(DOCS, 'index.html'), fragment);
rewrite(join(DOCS, 'os.html'), fragment);
