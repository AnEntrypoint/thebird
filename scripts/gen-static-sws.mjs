#!/usr/bin/env node
// Generates docs/sw-i1/index.js .. docs/sw-i50/index.js — thin per-instance
// Service Worker stubs. Each lives at its own scope path so registration
// doesn't need the Service-Worker-Allowed header (script-inside-scope rule),
// which matters on GH Pages (no custom headers). `importScripts` of a script
// OUTSIDE the registered scope is allowed — only the registered script URL
// itself must be inside scope — so the stub just imports the shared
// docs/sw-instance.js, which already derives INSTANCE_ID from
// self.registration.scope at runtime. No per-file body duplication needed.
//
// Re-run after moving/renaming docs/sw-instance.js. Output is committed.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import { MAX_RESTORE_INSTANCES } from '../docs/lib/instance-cap.js';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const repo = path.resolve(__dirname, '..');
// Matches os-shell.js's MAX_RESTORE_INSTANCES: fewer static SWs than the
// restore cap silently falls back every instance past this count to the dynamic
// sw-instance.js?inst= route, which needs a custom header GH Pages cannot serve.
const COUNT = MAX_RESTORE_INSTANCES;

let written = 0;
for (let i = 1; i <= COUNT; i++) {
    const id = 'i' + i;
    const stub =
        "// AUTO-GENERATED by scripts/gen-static-sws.mjs. DO NOT EDIT.\n" +
        "// Thin stub: the registered script lives inside this scope (GH-Pages-safe,\n" +
        "// no Service-Worker-Allowed header needed); importScripts of the shared\n" +
        "// sw-instance.js (outside this scope) is allowed since only the registered\n" +
        "// script URL itself must be inside scope. sw-instance.js derives its\n" +
        "// INSTANCE_ID from self.registration.scope at runtime.\n" +
        "importScripts('../sw-instance.js');\n";
    const dir = path.join(repo, 'docs', 'sw-' + id);
    await fs.mkdir(dir, { recursive: true });
    await fs.writeFile(path.join(dir, 'index.js'), stub, 'utf8');
    written++;
}
console.log('[gen-static-sws] wrote ' + written + ' stub files under docs/sw-i{1..' + COUNT + '}/index.js');

// Fail loudly if any stub directory for the full 1..COUNT range is missing —
// a partial write here would silently fall every instance past the gap back
// to the dynamic sw-instance.js?inst= route, which GH Pages cannot serve
// (custom-header requirement). Catches truncated runs, disk errors, or a
// COUNT bump that didn't get regenerated/committed.
const missing = [];
for (let i = 1; i <= COUNT; i++) {
    const id = 'i' + i;
    const stubPath = path.join(repo, 'docs', 'sw-' + id, 'index.js');
    try {
        await fs.access(stubPath);
    } catch {
        missing.push('sw-' + id);
    }
}
if (missing.length) {
    console.error('[gen-static-sws] FATAL: missing stub dirs after generation: ' + missing.join(', '));
    process.exit(1);
}
