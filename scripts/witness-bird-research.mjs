#!/usr/bin/env node
// HEADLINE GOAL WITNESS (deterministic): freddie researches a bird, writes a
// vibe-coded site into thebird's IndexedDB filesystem, and the site is retrievable
// + displayable. Drives the REAL freddie host tool surface directly (the same
// host.pi.tools the agent loop uses) so the witness does not depend on a slow,
// non-deterministic multi-turn LLM tool loop:
//   1. boot thebird + freddie, wait for window.__freddieRuntimeBridge.host (set by
//      createFreddieChat once ensureHost resolves on dashboard mount)
//   2. host.pi.tools web_search('<bird>') -> research text (real DDG fetch)
//   3. host.pi.tools write(path, vibe-coded html embedding the research) -> IDB FS
//   4. host.fs.readFile(path) -> assert the file persisted with bird content
//   5. parse the html and assert displayable innerText carries the bird
import { bootBrowser, sleep, assert, printReportAndExit } from './witness-lib.mjs';
const BIRD = process.argv[3] || 'emperor penguin';
const SITE = '/sites/bird.html';
const { browser, page, errs } = await bootBrowser({ tag: 'br', viewport: { width: 1400, height: 900 }, settleMs: 11000 }); // past SW-claim reload
const ev = async (fn, ...a) => { try { return await page.evaluate(fn, ...a); } catch (e) { return { _detached: String(e.message).slice(0, 60) }; } };

// Open the chat app — createFreddieChat runs ensureHost(instance) which sets
// globalThis.__freddieRuntimeBridge = { host }. The dashboard alone does not.
for (let i = 0; i < 30; i++) { const r = await ev(() => !!window.__debug?.shell); if (r === true) break; await sleep(1500); }
await ev(async () => { try { await window.__debug.shell.openApp('chat'); } catch { /* swallow: best-effort open; the following host-bridge poll loop times out and reports host:false if this never mounted */ } });

// wait for the freddie host bridge (set once ensureHost resolves)
let host = false;
for (let i = 0; i < 120; i++) {
  const r = await ev(() => !!(window.__freddieRuntimeBridge?.host?.pi?.tools));
  if (r === true) { host = true; break; }
  await sleep(2000);
}

const result = await ev(async (bird, site) => {
  const host = window.__freddieRuntimeBridge?.host;
  if (!host?.pi?.tools) return { err: 'no host.pi.tools' };
  const tools = host.pi.tools;
  const names = [...(tools.keys ? tools.keys() : [])];
  const call = async (name, args) => {
    // tools may be a Map (host.pi.tools.get(name).handler/run) or a list
    let t = tools.get ? tools.get(name) : null;
    if (!t && tools.list) t = tools.list().find(x => (x.name || x.schema?.function?.name) === name);
    if (!t) return { _missing: name };
    const h = t.handler || t.run || t.fn || t;
    return await h(args);
  };
  // 1. research (real web_search tool)
  let research = '';
  try { const ws = await call('web_search', { query: bird + ' facts habitat diet' }); research = typeof ws === 'string' ? ws : JSON.stringify(ws); }
  catch (e) { research = 'web_search-err: ' + e.message; }
  // 2. vibe-coded site embedding the research
  const html = `<!doctype html><html><head><meta charset=utf8><title>${bird}</title>
<style>:root{color-scheme:dark}body{font:16px/1.6 system-ui;max-width:680px;margin:2rem auto;padding:1rem;background:#0b1020;color:#e6edf3}
h1{color:#58d68d;border-bottom:2px solid #1f6f43;padding-bottom:.3rem}article{white-space:pre-wrap}</style></head>
<body><h1>${bird} — field research</h1><article id=research>${String(research).slice(0,2000).replace(/[<>]/g,' ')}</article>
<footer>Researched + generated by freddie inside thebird.</footer></body></html>`;
  // 3. write to IDB FS via the write tool (fallback to fs.writeFile)
  let wrote = false;
  try { await call('write', { path: site, content: html }); wrote = 'tool'; }
  catch { try { host.fs.writeFile(site, html); wrote = 'fs'; } catch (e) { wrote = 'err:' + e.message; } }
  if (wrote === false || String(wrote).startsWith('err')) { try { host.fs.writeFile(site, html); wrote = 'fs2'; } catch { /* swallow: last-ditch fallback write already recorded as failed via wrote='err:...'; nothing more to report if this retry also throws */ } }
  // 4. read back
  let readBack = null; try { readBack = host.fs.readFile(site); } catch (e) { readBack = 'read-err:' + e.message; }
  // 5. displayable check
  let display = null;
  if (typeof readBack === 'string') {
    const doc = new DOMParser().parseFromString(readBack, 'text/html');
    const txt = doc.body ? (doc.body.innerText || doc.body.textContent) : '';
    display = { len: readBack.length, title: doc.title, innerTextHasBird: txt.toLowerCase().includes(bird.toLowerCase()), snippet: txt.slice(0, 160) };
  }
  return { toolNames: names, researchLen: String(research).length, researchSnippet: String(research).slice(0, 140), wrote, readBackLen: typeof readBack === 'string' ? readBack.length : readBack, display };
}, BIRD, SITE);

console.log('HOST-READY:', host);
console.log('RESULT:', JSON.stringify(result, null, 2));
console.log('ERRS:', errs.slice(0, 6));

const report = {};
assert(report, 'hostReady', host, 'freddie host bridge (window.__freddieRuntimeBridge.host.pi.tools) never became available');
report.raw = result;
assert(report, 'toolCallSucceeded', !!(result && !result.err), result && result.err ? result.err : 'no result from tool call');
assert(report, 'wroteFile', !!(result && result.wrote && !String(result.wrote).startsWith('err')), 'write to IDB FS failed: ' + (result && result.wrote));
assert(report, 'readBackLen', !!(result && result.readBackLen > 100), 'read-back file too short/absent: ' + (result && result.readBackLen));
assert(report, 'innerTextHasBird', !!(result && result.display && result.display.innerTextHasBird), 'rendered innerText does not contain the researched bird name');
report.errors = errs.slice(0, 6);

await browser.close();
printReportAndExit(report);
